#!/usr/bin/env python3
"""
Generate golden test vectors from the simulator for the firmware control library.

The C++ Controller (firmware/lib/tm_control) must reproduce, tick by tick, what the Python
reference controller (thermal_sim.TermoMade + Schedule) does when fed the same sensor values:
same setpoint, same demand u (to 1e-6) and the same valve state.

Usage: python3 gen_golden.py ../../firmware/test/test_golden/golden_data.h
"""
import sys
import thermal_sim as S


class Recorder:
    """Sits between Schedule and the controller: records what the controller saw and did."""

    def __init__(self, inner):
        self.inner, self.name, self.rows = inner, inner.name, []

    @property
    def u(self):
        return self.inner.u

    def tick(self, sp, meas, dt):
        on = self.inner.tick(sp, meas, dt)
        self.rows.append((sp, meas, self.inner.u, 1 if on else 0))
        return on


def run(name, days, schedule=None, eff=False, **kw):
    inner = S.make("termomade", eff=eff)
    rec = Recorder(inner)
    ctrl = S.Schedule(rec, **schedule) if schedule else rec
    S.simulate(ctrl, days=days, eval_from_h=0, **kw)
    return name, rec.rows, schedule


SCENARIOS = [
    run("steady_winter", 1.5, T_out_mean=-2.0),
    run("cold_arrival", 1.0, T_out_mean=-2.0, T0_air=8.0, T0_mass=8.0),
    run("night_eff_preheat", 2.5, schedule=dict(sp_night=17.0, preheat_h=2.0), eff=True, T_out_mean=-2.0),
    run("mild_fast_night185", 1.5, schedule=dict(sp_night=18.5), eff=False, T_out_mean=8.0),
]


def main(out):
    with open(out, "w") as f:
        f.write("// GENERATED by tools/sim/gen_golden.py - do not edit.\n")
        f.write("// Per controller tick (30 s): setpoint x100, measurement x100, demand u, valve open.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("struct GoldenRow { int16_t sp100; int16_t meas100; double u; uint8_t open; };\n")
        f.write("struct GoldenScenario { const char* name; const GoldenRow* rows; int n; "
                "bool schedule; double sp_night; int preheat_min; bool efficient; };\n\n")
        for name, rows, sch in SCENARIOS:
            f.write(f"static const GoldenRow g_{name}[] = {{\n")
            for sp, meas, u, on in rows:
                f.write(f"{{{round(sp*100)},{round(meas*100)},{u:.9f},{on}}},\n")
            f.write("};\n\n")
        f.write("static const GoldenScenario g_scenarios[] = {\n")
        for name, rows, sch in SCENARIOS:
            eff = "true" if name.startswith("night_eff") else "false"
            if sch:
                f.write(f'  {{"{name}", g_{name}, {len(rows)}, true, {sch["sp_night"]}, '
                        f'{int(round(sch.get("preheat_h", 0.0) * 60))}, {eff}}},\n')
            else:
                f.write(f'  {{"{name}", g_{name}, {len(rows)}, false, 0.0, 0, false}},\n')
        f.write("};\n")
    total = sum(len(r) for _, r, _ in SCENARIOS)
    opens = sum(sum(1 for i in range(1, len(r)) if r[i][3] and not r[i-1][3]) for _, r, _ in SCENARIOS)
    print(f"wrote {out}: {len(SCENARIOS)} scenarios, {total} ticks, {opens} valve openings")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "golden_data.h")
